#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn flags_are_single_bits() {
        for class in ["trigger_once", "func_door", "func_door_rotating", "prop_physics", "prop_dynamic", "logic_relay", "ambient_generic", "light_spot", "func_rotating", "func_tracktrain", "func_button", "env_fade", "env_shake", "env_sprite", "env_spark", "point_spotlight", "point_template", "trigger_changelevel", "path_track"] {
            let f = flags(class);
            assert!(!f.is_empty(), "{class}");
            for (k, &(bit, _)) in f.iter().enumerate() {
                assert!(bit.is_power_of_two(), "{class}: {bit}");
                assert!(f[..k].iter().all(|&(b, _)| b != bit), "{class}: {bit} twice");
            }
        }
    }

    /// Every key Portal's maps use often (on a class) has something said about it.
    #[test]
    fn the_maps_keys_are_described() {
        let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("levels/portal");
        let mut count: std::collections::HashMap<(String, String), usize> = std::collections::HashMap::new();
        for e in std::fs::read_dir(dir).unwrap().flatten() {
            let Ok(text) = std::fs::read_to_string(e.path()) else { continue };
            let Ok(doc) = aperture::doc::LevelDoc::from_ron(&text) else { continue };
            for o in &doc.objects {
                if let aperture::doc::Kind::Entity { class, keys, .. } = &o.kind {
                    for (k, _) in keys {
                        *count.entry((class.clone(), k.to_ascii_lowercase())).or_default() += 1;
                    }
                }
            }
        }
        let mut missing: Vec<String> = count.iter().filter(|((c, k), n)| **n >= 10 && describe(c, k).is_none()).map(|((c, k), n)| format!("{c}.{k} ({n})")).collect();
        missing.sort();
        assert!(missing.is_empty(), "keys with nothing said about them: {missing:?}");
    }
}
